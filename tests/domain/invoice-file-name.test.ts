// 'PDF 로 저장' 의 기본 파일명. (사용자 결정 2026-08-13)
//   크롬은 창 제목을 파일명으로 씁니다.
// =========================================================

import { describe, it, expect } from 'vitest';
import { invoiceFileName } from '@/server/domain/billing';

describe('청구서 파일명', () => {
  it('문서·거래처·달을 잇는다', () => {
    expect(invoiceFileName('청구서', '한빛치과', '2026-08')).toBe('청구서_한빛치과_2026-08');
  });

  it('기공료 청구서도 그대로', () => {
    expect(invoiceFileName('청구서 (기공료)', '케이덴탈랩', '2026-08')).toBe(
      '청구서 (기공료)_케이덴탈랩_2026-08',
    );
  });

  it('★ 파일명에 못 쓰는 글자를 뺀다 — 저장이 막히거나 이름이 잘립니다', () => {
    expect(invoiceFileName('청구서', '한빛/서울:치과', '2026-08')).toBe(
      '청구서_한빛서울치과_2026-08',
    );
    expect(invoiceFileName('청구서', '치과<*?>', '2026-08')).toBe('청구서_치과_2026-08');
  });

  it('괄호와 점은 남긴다 — 상호에 흔합니다', () => {
    expect(invoiceFileName('청구서', '(주)한빛덴탈.강남', '2026-08')).toBe(
      '청구서_(주)한빛덴탈.강남_2026-08',
    );
  });

  it('빈 칸은 건너뛴다 — 밑줄이 겹치면 안 됩니다', () => {
    expect(invoiceFileName('청구서', '', '2026-08')).toBe('청구서_2026-08');
    expect(invoiceFileName('청구서', '   ', '2026-08')).toBe('청구서_2026-08');
  });
});
