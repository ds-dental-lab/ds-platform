-- DS Flow — 주문 상태에 '업로드중' 을 더합니다 (작업지시서 §3-3)
-- 파일 위치: supabase/migrations/<타임스탬프>_status_uploading_value.sql
--
-- ★★ **값을 더하는 것만** 여기서 합니다.
--   Postgres 는 열거형에 값을 더한 **같은 트랜잭션 안에서 그 값을
--   쓰지 못합니다.** 규칙(트리거·정책)까지 한 파일에 몰아넣으면
--   "unsafe use of new value of enum type" 으로 통째로 거절합니다.
--   그래서 값 하나만 올리고, 쓰는 것은 다음 파일에서 합니다.
--
-- ★ 자리는 'received' **앞**입니다. 열거형의 순서가 곧 정렬 순서라,
--   뒤에 붙이면 주문목록을 상태로 정렬했을 때 업로드중이 맨 끝에
--   섭니다 — 접수보다 먼저인 단계인데요.
-- =========================================================

alter type order_status add value if not exists 'uploading' before 'received';
