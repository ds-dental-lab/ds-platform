-- =========================================================
-- 자사 제작이면 디자인센터가 수거완료를 누를 수 있어야 합니다.
-- (사용자 지적 2026-08-13 — "기공소 또는 기공소 권한이 있는
--  디자인센터 계정이 권한을 가지는게 맞다고 봐")
--
-- ★ 지금 정책이 조직의 **종류**를 봅니다.
--     using (lab_org_id = my_org_id() and my_org_type() = 'lab')
--   그런데 자사 제작이면 주문의 lab_org_id 가 **디자인센터 자신**입니다
--   (통합 조직 모델, 설계서 Q-6). 물건은 디자인센터가 받는데 계정
--   종류가 'design_center' 라서 **아무도 수거완료를 못 눌렀습니다.**
--   수거가 안 닫히면 제작 시작도 막히므로 그 주문은 그대로 굳습니다.
--
-- ★ 그래서 **자리**로만 봅니다 — `lab_org_id = my_org_id()`.
--   치과는 여기에 걸리지 않습니다. 치과 조직이 주문의 기공소가 되는
--   길이 없습니다. 물건을 보내는 쪽이 도착을 선언할 수는 없습니다.
--
-- ★ 문이 넓어지지 않는지 확인했습니다 (아래 rollback 테스트).
--   기공소가 남의 건을 닫기 · 치과가 자기 건을 닫기 둘 다 여전히 막힙니다.
-- =========================================================

drop policy if exists pickup_update on pickup_requests;

create policy pickup_update on pickup_requests
  for update
  using (lab_org_id = my_org_id())
  with check (lab_org_id = my_org_id());
