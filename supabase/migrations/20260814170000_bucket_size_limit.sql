-- 버킷에 파일 한 개 상한을 겁니다 (사용자 요청 2026-08-14 — 저장소 아끼기)
--
-- ★ 화면에는 이미 100MB 검사가 있었습니다. 그런데 그건 **부탁**입니다.
--   주소를 직접 부르면 그대로 지나갑니다. 버킷에 걸어야 자물쇠입니다.
--   무료 요금제의 전체 한도가 1GB 인데, 한 번의 실수로 그 절반이
--   찰 수 있는 상태였습니다.
--
-- ★ 화면 값(domain/upload 의 MAX_UPLOAD_BYTES)과 **같은 숫자**입니다.
--   달라지면 화면은 받아 놓고 저장소가 뱉어서, 사람은 왜 안 되는지
--   모른 채 같은 파일을 다시 올립니다.
--
-- ★ 형식(mime) 제한은 **일부러 안 겁니다.**
--   치과가 올리는 것이 대개 `application/octet-stream` 이거나 아예
--   빈 값으로 옵니다 — `.dxd` `.stl` `.constructioninfo` 가 그렇습니다.
--   그걸 허용 목록에 넣으면 결국 아무거나 허용하는 것과 같아집니다.
--   게다가 설계 파일로 **exocad webview(`.html`, 5MB)** 가 실제로
--   올라옵니다. 목록을 좁게 잡으면 그게 먼저 막힙니다.
-- =========================================================

update storage.buckets
   set file_size_limit = 104857600   -- 100MB
 where id = 'order-files';
