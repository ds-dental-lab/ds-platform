-- =========================================================
-- 알림톡 받을 사람과 번호. (사용자 요청 2026-08-14)
--
-- ★ **대표번호와 다릅니다.**
--   organizations.tel 은 청구서에 찍히는 번호입니다. 알림톡은 사람이
--   받으므로 사람마다 따로 둡니다 — 관리자든 사용자든 각자 자기 번호를
--   넣고, 각자 켜고 끕니다. 한 조직에서 여럿이 동시에 받습니다.
--
-- ★ 칸을 새로 안 만듭니다.
--   `user_profiles.phone` 이 처음부터 있었는데 **아무도 안 쓰고**
--   있었습니다(코드 전체를 훑어 확인). 뜻이 정확히 같으므로 그걸 씁니다.
--   비슷한 칸이 둘이면 언젠가 서로 다른 값이 들어갑니다.
--
-- ★ 켜고 끄는 칸만 새로 답니다.
--   번호가 비어 있으면 어차피 못 보내지만, **번호는 두고 잠시 끄는**
--   경우가 있습니다(휴가·야간). 번호를 지웠다 다시 넣게 하면 그때마다
--   오타가 납니다.
--
-- ★ 기본값은 **켜짐**입니다.
--   번호를 넣는 행위 자체가 "받겠다" 는 뜻입니다. 넣고 나서 왜 안 오는지
--   찾게 만들면 안 됩니다. 번호가 없으면 켜져 있어도 안 나갑니다.
--
-- ★ 정책은 새로 안 만듭니다.
--   `profile_update` 가 이미 `id = auth.uid()` 로 **자기 줄만** 고치게
--   하고 있습니다. 사용자도 스스로 번호를 고칠 수 있어야 한다는 요구가
--   그것으로 이미 충족됩니다. 남의 번호는 못 건드립니다.
-- =========================================================

alter table user_profiles
  add column if not exists alimtalk_on boolean not null default true;

comment on column user_profiles.phone is
  '알림톡 받을 번호. 숫자만 담습니다(01012345678). 비어 있으면 안 보냅니다';

comment on column user_profiles.alimtalk_on is
  '알림톡을 받을 것인가. 번호를 지우지 않고 잠시 끌 때 씁니다';
