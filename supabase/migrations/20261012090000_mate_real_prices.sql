-- DS Flow — 메이트 치과의 **시험값**을 걷어내고 진짜 단가를 앞당깁니다
-- 파일 위치: supabase/migrations/20261012090000_mate_real_prices.sql
-- 기준: 사용자 확인 2026-10-12 — "테스트값이였어 / 1당 4000으로 계산하면된다 / 2는 8000"
--
-- ★★ 무슨 일이었나 — 메이트 치과 단가가 **1원·2원**으로 들어가 있었습니다.
--   진짜 거래가가 아니라 길을 뚫어 보려고 넣은 시험값입니다. 오늘(10-12)
--   진짜 값(4,000 / 8,000)을 넣으셨는데, 2026-10-10 에 들어간 규칙대로
--   **오늘부터 배송되는 건**에만 적용됩니다. 그래서 10월 배송분 두 건이
--   46원으로 서 있었습니다.
--
-- ★ 1 → 4,000, 2 → 8,000, 폰틱 1 → 4,000 으로 **한 줄도 어긋나지 않고**
--   맞아떨어집니다(여덟 줄 전부 대조). 시험값을 치우고 진짜 값을 그
--   치과 단가가 처음 생긴 날부터 유효한 것으로 둡니다.
--
-- ★ 이렇게 하면 디자인센터 HOME 의 10월 이용금액이 46원 → **184,000원**
--   이 됩니다(성승윤 24,000 · 유제옥 160,000).
--
-- ★★ 이것은 **소급입니다.** 평소에는 하지 않습니다 — 단가는 배송일 기준이고
--   지나간 청구액은 안 흔드는 것이 원칙입니다(2026-10-10). 다만 저 값은
--   애초에 **청구할 생각이 없던 시험값**이라, '처음부터 진짜 값이었다' 가
--   사실에 더 가깝습니다. 마감된 기간도 없어 굳은 금액을 건드리지 않습니다.
-- =========================================================

-- ① 시험값 줄을 치웁니다 (먼저 — 아래 update 와 날짜가 겹칩니다)
delete from product_price_history
 where party_org_id = '01c6e95a-34f4-4f95-b8e6-f96212f698ab'
   and party_type   = 'clinic'
   and effective_from = date '2026-09-21';

-- ② 진짜 단가를 그 치과 단가가 처음 생긴 날부터로 당깁니다
--
-- ★ 이보다 앞서 배송된 건이 있어도 괜찮습니다 — 고르는 쪽(priceOn)이
--   모든 줄보다 이른 날짜면 **가장 오래된 줄**을 쓰기 때문입니다.
update product_price_history
   set effective_from = date '2026-09-21'
 where party_org_id = '01c6e95a-34f4-4f95-b8e6-f96212f698ab'
   and party_type   = 'clinic'
   and effective_from = date '2026-10-12';
