-- =========================================================
-- DS Flow — 저장소 파일 상한 300MB → 500MB
-- 파일 위치: supabase/migrations/20260820160000_bucket_500mb.sql
-- 기준: 작업지시서 2026-08-20 §3-1 확정값
--
-- ★ 오늘 아침 100 → 300MB 로 올렸는데, 지시서 확정값이 500MB 입니다.
--   실제 최대(한 덩어리 150MB)의 세 배 — 스캐너를 바꾸거나 케이스가
--   커지면 파일도 같이 큽니다. 다시 막히면 그때는 이미 거래 중입니다.
--
-- ★ 코드의 MAX_UPLOAD_BYTES 와 **같은 값**이어야 합니다.
--   화면이 먼저 걸러 주고, 버킷이 마지막으로 막습니다. 둘이 어긋나면
--   화면은 통과시켰는데 저장소가 튕기는, 설명할 수 없는 실패가 납니다.
--
-- ★ 주문당 총량 1GB 는 **버킷에 걸 수 없습니다** — 저장소는 파일
--   하나씩만 봅니다. 그건 화면(checkUploadBatch)이 봅니다.
--   여기서 막는 것은 '한 덩어리가 너무 큰 것' 뿐입니다.
-- =========================================================

update storage.buckets
   set file_size_limit = 524288000     -- 500MB
 where id = 'order-files';
