-- =========================================================
-- DS Flow — 저장소 파일 상한 100MB → 300MB
-- 파일 위치: supabase/migrations/20260820100000_bucket_300mb.sql
-- 기준: 사용자 확인 2026-08-20 —
--   "1건이 150MB 로 한 덩어리로 올 때도 있고, 3개로 각 50MB,
--    10개로 각 10MB 로 올 때도 있다"
--
-- ★ 150MB 짜리 한 덩어리가 **지금 상한(100MB)에 그대로 걸립니다.**
--   치과는 왜 안 올라가는지 모른 채 주문을 못 넣습니다.
--
-- ★ 실제 최대의 두 배로 잡습니다. 스캐너를 바꾸거나 케이스가 커지면
--   파일도 같이 큽니다 — 다시 막히면 그때는 이미 거래 중입니다.
--
-- ★ 코드의 MAX_UPLOAD_BYTES 와 **같은 값**이어야 합니다.
--   화면이 먼저 걸러 주고, 버킷이 마지막으로 막습니다. 둘이 어긋나면
--   화면은 통과시켰는데 저장소가 튕기는, 설명할 수 없는 실패가 납니다.
--
-- ★ mime 허용목록은 여전히 안 겁니다. 스캐너 파일은 브라우저가
--   application/octet-stream 이나 빈 값으로 보냅니다 — 목록을 걸면
--   .dxd·.stl 이 먼저 막힙니다. 크기로만 겁니다.
-- =========================================================

update storage.buckets
   set file_size_limit = 314572800     -- 300MB
 where id = 'order-files';
