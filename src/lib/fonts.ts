// ★ 왜 청구서에만 붙이는가.
//   앱 전체는 지금 한글 글꼴을 **하나도 안 정해 두고** 기계에 있는 것을
//   씁니다 (윈도우는 맑은 고딕, 맥은 애플 산돌고딕). 화면은 그래도
//   괜찮습니다 — 각자 자기 기계에서 익숙한 글자로 봅니다.
//   그런데 **청구서는 거래처에 나가는 문서**입니다. 우리 화면에서 보고
//   내보낸 PDF 가 받는 쪽 기계에서 다른 글꼴로 보이면, 줄이 밀리고
//   숫자 칸이 어긋납니다. 나가는 문서만은 어디서 열어도 같아야 합니다.
//
// ★ next/font/google 은 **빌드할 때 받아 우리 서버에 둡니다.**
//   화면을 열 때 구글에 요청하지 않습니다 — 거래처 브라우저가 남의
//   서버를 부르지 않고, 느려지지도 않습니다.
//
// ★ 라이선스.
//   나눔고딕은 SIL Open Font License 입니다. 상업적 사용·임베딩·재배포가
//   모두 허용되고, 글꼴 자체를 파는 것만 금지입니다. PDF 에 심어
//   거래처에 보내는 것은 허용 범위 안입니다.
//
// ★ preload 를 끕니다.
//   한글 글꼴은 조각이 아주 많습니다. 모든 화면에서 미리 받으면
//   청구서를 안 보는 사람까지 값을 치릅니다. 청구서를 열 때 받습니다.
// =========================================================

import { Nanum_Gothic } from 'next/font/google';

export const invoiceFont = Nanum_Gothic({
  weight: ['400', '700'],
  /*
    ★ 'korean' 은 **적을 수가 없습니다.** 타입이 'latin' 만 받습니다.
      그래서 한글이 안 실리는 것 아닌가 의심했는데, 빌드 결과를 열어
      확인했습니다 — 한글은 그대로 받아집니다.

        @font-face 184개 · woff2 196개 (2.1MB) · 평균 11KB
        unicode-range 에 U+AC00-D7A3 등 한글 구간이 들어 있음

      subsets 는 **미리 받아 둘** 묶음을 고르는 값일 뿐이고, 글꼴 파일은
      구글이 준 CSS 에 적힌 것을 전부 우리 쪽에 둡니다.

    ★ 2.1MB 를 다 내려받지 않습니다.
      한글 글꼴은 조각조각 잘려 있고 브라우저는 **그 문서에 나온 글자가
      든 조각만** 가져옵니다. 청구서 한 장이면 대개 열 개 안팎입니다.

    ★ 이 줄을 고칠 일이 생기면 위 숫자를 **다시 세어 보세요.**
      한글이 빠져도 화면은 멀쩡해 보입니다 (기계 글꼴로 조용히 떨어짐).
  */
  subsets: ['latin'],
  variable: '--font-invoice',
  display: 'swap',
  preload: false,
  // 글꼴이 안 받아졌을 때 기계에 있는 것으로 버팁니다
  fallback: ['Malgun Gothic', 'Apple SD Gothic Neo', 'sans-serif'],
});
