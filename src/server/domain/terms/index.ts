/** 화면이 받는 값 — DB 함수 public_terms 가 주는 그대로 */
export interface TermsFacts {
  orgName: string | null;
  bizNo: string | null;
  address: string | null;
  tel: string | null;
  email: string | null;
  effectiveOn: string | null;
}

/**
 * 아직 공개할 수 없는 상태인가.
 *
 * ★ 처리방침과 같은 규칙입니다. 시행일을 넣는 행위가 곧
 *   "법률 검토를 마쳤다" 는 뜻입니다.
 */
export function isDraft(facts: TermsFacts): boolean {
  return !facts.effectiveOn;
}

/** 채워야 하는데 빈 곳 — 관리 화면이 이걸로 잔소리합니다 */
export function missingTermsFields(facts: TermsFacts): string[] {
  const out: string[] = [];

  if (!facts.bizNo?.trim()) out.push('사업자등록번호');
  if (!facts.address?.trim()) out.push('주소');
  if (!facts.tel?.trim() && !facts.email?.trim()) out.push('문의 연락처');
  if (!facts.effectiveOn) out.push('시행일');

  return out;
}

